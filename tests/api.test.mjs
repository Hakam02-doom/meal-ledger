import assert from 'node:assert/strict';
const origin=process.env.TEST_ORIGIN||'http://127.0.0.1:3000';
if(!['127.0.0.1','localhost'].includes(new URL(origin).hostname))throw Error('API tests are restricted to a local test server.');
const get=await fetch(origin+'/api/workspace');
assert.equal(get.status,401,'Configure a test Supabase project first; anonymous access must return 401.');
const forged=await fetch(origin+'/api/workspace',{headers:{'oai-authenticated-user-id':'fake','oai-authenticated-user-email':'fake@example.test'}});
assert.equal(forged.status,401,'Sites identity headers must never authenticate a Vercel request.');
const crossOrigin=await fetch(origin+'/api/workspace',{method:'POST',headers:{Origin:'https://untrusted.example','Content-Type':'application/json'},body:JSON.stringify({action:'lock'})});
assert.equal(crossOrigin.status,403);
console.log('PASS: anonymous access rejected, forged identity headers ignored, cross-origin mutation rejected.');
